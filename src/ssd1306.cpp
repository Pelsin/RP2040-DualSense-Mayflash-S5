static void cmd(uint8_t c) {
    uint8_t b[2] = { 0x00, c };
    i2c_write_blocking(DISPLAY_I2C, DISPLAY_I2C_ADDR, b, 2, false);
}

bool ssd1306_init(void) {
    i2c_init(DISPLAY_I2C, DISPLAY_I2C_HZ);
    gpio_set_function(DISPLAY_SDA_PIN, GPIO_FUNC_I2C);
    gpio_set_function(DISPLAY_SCL_PIN, GPIO_FUNC_I2C);
    gpio_pull_up(DISPLAY_SDA_PIN);
    gpio_pull_up(DISPLAY_SCL_PIN);

    // Probe for ACK.
    uint8_t dummy = 0;
    if (i2c_write_blocking(DISPLAY_I2C, DISPLAY_I2C_ADDR, &dummy, 1, false) < 0) {
        return false;
    }

    static const uint8_t seq[] = {
        0xAE,             // display off
        0x20, 0x00,       // horizontal addressing mode
        0xB0,             // page start
        0xC8,             // COM scan dec
        0x00, 0x10,       // low/high column
        0x40,             // start line 0
        0x81, 0x7F,       // contrast
        0xA1,             // segment remap
        0xA6,             // normal display
        0xA8, 0x3F,       // multiplex 1/64
        0xD3, 0x00,       // display offset
        0xD5, 0x80,       // clock div
        0xD9, 0xF1,       // precharge
        0xDA, 0x12,       // com pins
        0xDB, 0x40,       // vcom detect
        0x8D, 0x14,       // charge pump on
        0xAF,             // display on
    };
    for (unsigned i = 0; i < sizeof(seq); i++) cmd(seq[i]);

    ssd1306_clear();
    ssd1306_show();
    return true;
}

void ssd1306_clear(void) {
    memset(s_fb, 0, sizeof(s_fb));
}

void ssd1306_text(uint8_t x, uint8_t row, const char *s) {
    if (row >= SSD1306_PAGES) return;
    uint8_t *line = &s_fb[row * SSD1306_W];
    while (*s && x < SSD1306_W) {
        char c = *s++;
        if (c < 0x20 || c > 0x7A) c = 0x20;
        const uint8_t *g = kFont5x7[c - 0x20];
        for (int i = 0; i < 5 && x < SSD1306_W; i++) line[x++] = g[i];
        if (x < SSD1306_W) line[x++] = 0x00; // 1px gap
    }
}

void ssd1306_pixel(int x, int y, bool on) {
    if ((unsigned)x >= SSD1306_W || (unsigned)y >= SSD1306_H) return;
    uint8_t *p = &s_fb[(y >> 3) * SSD1306_W + x];
    uint8_t bit = (uint8_t)(1u << (y & 7));
    if (on) *p |= bit; else *p &= (uint8_t)~bit;
}

void ssd1306_fill_rect(int x, int y, int w, int h, bool on) {
    for (int yy = y; yy < y + h; yy++)
        for (int xx = x; xx < x + w; xx++)
            ssd1306_pixel(xx, yy, on);
}

void ssd1306_rect(int x, int y, int w, int h, bool on) {
    for (int xx = x; xx < x + w; xx++) {
        ssd1306_pixel(xx, y, on);
        ssd1306_pixel(xx, y + h - 1, on);
    }
    for (int yy = y; yy < y + h; yy++) {
        ssd1306_pixel(x, yy, on);
        ssd1306_pixel(x + w - 1, yy, on);
    }
}

int ssd1306_text_scaled(int x, int y, const char *s, uint8_t scale, bool on) {
    while (*s) {
        char c = *s++;
        if (c < 0x20 || c > 0x7A) c = 0x20;
        const uint8_t *g = kFont5x7[c - 0x20];
        for (int col = 0; col < 5; col++) {
            uint8_t bits = g[col];
            for (int row = 0; row < 8; row++) {
                if (bits & (1u << row))
                    ssd1306_fill_rect(x + col * scale, y + row * scale, scale, scale, on);
            }
        }
        x += 6 * scale;  // 5 columns + 1 column gap
    }
    return x;
}

void ssd1306_show(void) {
    cmd(0x21); cmd(0x00); cmd(0x7F);             // column range 0..127
    cmd(0x22); cmd(0x00); cmd(SSD1306_PAGES - 1); // page range 0..7

    // Stream the framebuffer in chunks with a 0x40 data prefix.
    uint8_t chunk[1 + 16];
    for (unsigned i = 0; i < sizeof(s_fb); i += 16) {
        chunk[0] = 0x40;
        memcpy(&chunk[1], &s_fb[i], 16);
        i2c_write_blocking(DISPLAY_I2C, DISPLAY_I2C_ADDR, chunk, sizeof(chunk), false);
    }
}
